int vkewInit(const VKEWSettings* lpArgs)
{
	VkResult err;
	const char* enabledExtensions[VKEW_MAX_EXTENSIONS];
	const char* validationLayerNames[VKEW_MAX_LAYERS];
	Vulkan.settings = *lpArgs;
	Vulkan.validationLayerNames = validationLayerNames;
	Vulkan.validationLayerCount = 0;
	Vulkan.enabledExtensions = enabledExtensions;
	Vulkan.enabledExtensionCount = 0;

	VkApplicationInfo applicationInfo = { 0 };
	VkInstanceCreateInfo instanceCreateInfo = { 0 };
	Vulkan.enableValidation = Vulkan.settings.enableValidation != 0;
	Vulkan.enableRaytracing = Vulkan.settings.enableRaytracing;
#if defined VK_NO_PROTOTYPES
#if defined(_WIN32)
#ifdef UNICODE
	Vulkan.ctx = LoadLibrary(L"vulkan-1.dll");
#else
	Vulkan.ctx = LoadLibrary("vulkan-1.dll");
#endif
#elif defined(UNIX)
	Vulkan.ctx = dlopen("libvulkan.so", RTLD_NOW | RTLD_LOCAL);
#elif defined(NX)
	Vulkan.ctx = dlopen("libvulkan.so", RTLD_NOW | RTLD_LOCAL);
#endif
	if (!Vulkan.ctx)
	{
		return VK_ERROR_INITIALIZATION_FAILED;
	}
#endif
#if defined VK_NO_PROTOTYPES
	// Load base function pointers
	VKEW_GET_PROC(vkEnumerateInstanceExtensionProperties);
	VKEW_GET_PROC(vkEnumerateInstanceLayerProperties);
	VKEW_GET_PROC(vkCreateInstance);
	VKEW_GET_PROC(vkGetInstanceProcAddr);
	VKEW_GET_PROC(vkGetDeviceProcAddr);
#endif
	applicationInfo.sType = VK_STRUCTURE_TYPE_APPLICATION_INFO;
	applicationInfo.pNext = NULL;
	applicationInfo.pApplicationName = Vulkan.settings.pApplicationName;
	applicationInfo.applicationVersion = Vulkan.settings.applicationVersion;
	applicationInfo.pEngineName = Vulkan.settings.pEngineName;
	applicationInfo.engineVersion = Vulkan.settings.engineVersion;
	applicationInfo.apiVersion = Vulkan.settings.apiVersion;

	if (!Vulkan.settings.pAllocator)
	{
		Vulkan.allocationCallbacks.pfnAllocation = vkewDefaultAlloc;
		Vulkan.allocationCallbacks.pfnReallocation = vkewDefaultRealloc;
		Vulkan.allocationCallbacks.pfnFree = vkewDefaultFree;
		Vulkan.allocationCallbacks.pfnInternalAllocation = vkewDefaultInternalAlloc;
		Vulkan.allocationCallbacks.pfnInternalFree = vkewDefaultInternalFree;
		Vulkan.allocationCallbacks.pUserData = NULL;
	}
	else
	{
		Vulkan.allocationCallbacks = *Vulkan.settings.pAllocator;
	}


	int enableValidation = InitValidationLayers(Vulkan.settings.enableValidation);

	InitExtensionsLayers(enableValidation);
	instanceCreateInfo.sType = VK_STRUCTURE_TYPE_INSTANCE_CREATE_INFO;
	instanceCreateInfo.pNext = NULL;
	instanceCreateInfo.flags = 0;
	instanceCreateInfo.pApplicationInfo = &applicationInfo;
	instanceCreateInfo.enabledLayerCount = Vulkan.validationLayerCount;
	instanceCreateInfo.ppEnabledLayerNames = Vulkan.validationLayerNames;
	instanceCreateInfo.enabledExtensionCount = Vulkan.enabledExtensionCount;
	instanceCreateInfo.ppEnabledExtensionNames = Vulkan.enabledExtensions;
	Vulkan.appInfo = applicationInfo;
	Vulkan.instanceCreateInfo = instanceCreateInfo;
	if (enableValidation)
	{
		InitDebugReport();
	}


	err = VK_CHECK(vkCreateInstance(&Vulkan.instanceCreateInfo,
		&Vulkan.allocationCallbacks, // If pAllocator is not NULL, pAllocator must be a pointer to a valid VkAllocationCallbacks structure
		&Vulkan.i.instance)); //pInstance points a VkInstance handle in which the resulting instance is returned.
	if (err == VK_ERROR_INCOMPATIBLE_DRIVER)
	{
		LogMessage(VKEW_MESSAGE_VERBOSE,
			"Cannot find a compatible Vulkan installable client driver (ICD).\n\n"
			"Please look at the Getting Started guide for additional information.\n",
			"vkCreateInstance Failure");
	}
	else if (err == VK_ERROR_EXTENSION_NOT_PRESENT)
	{
		LogMessage(VKEW_MESSAGE_VERBOSE,
			"Cannot find a specified extension library.\n"
			"Make sure your layers path is set appropriately.\n",
			"vkCreateInstance Failure");
	}
	else if (err)
	{
		LogMessage(VKEW_MESSAGE_VERBOSE,
			"vkCreateInstance failed.\n\n"
			"Do you have a compatible Vulkan installable client driver (ICD) installed?\n"
			"Please look at the Getting Started guide for additional information.\n",
			"vkCreateInstance Failure");
	}
	if (err == VK_SUCCESS)
	{
		vkewInterfaceLevelInit(Vulkan.i);
		if (enableValidation)
		{
			ActivateDebugReport();
		}
	}
	return err;
}
